-- Social Media Manager for Shorlah Cloud portfolio.
-- Run once in Supabase SQL Editor as the project owner.
create table if not exists public.social_links (
  id bigint generated by default as identity primary key,
  platform text not null check (char_length(platform) between 1 and 80),
  label text not null check (char_length(label) between 1 and 80),
  url text not null check (url ~* '^https?://'),
  placement text not null default 'footer' check (placement in ('header','footer','contact')),
  icon text not null default 'Other' check (icon in ('Instagram','LinkedIn','GitHub','YouTube','Facebook','Website','Other')),
  visible boolean not null default true,
  display_order integer not null default 10,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.social_links enable row level security;
drop policy if exists "Public can read visible social links" on public.social_links;
create policy "Public can read visible social links" on public.social_links
  for select to anon, authenticated using (visible = true);
drop policy if exists "Admins can read all social links" on public.social_links;
create policy "Admins can read all social links" on public.social_links
  for select to authenticated using ((select public.is_admin()));
drop policy if exists "Admins can insert social links" on public.social_links;
create policy "Admins can insert social links" on public.social_links
  for insert to authenticated with check ((select public.is_admin()));
drop policy if exists "Admins can update social links" on public.social_links;
create policy "Admins can update social links" on public.social_links
  for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists "Admins can delete social links" on public.social_links;
create policy "Admins can delete social links" on public.social_links
  for delete to authenticated using ((select public.is_admin()));
grant select on public.social_links to anon, authenticated;
grant insert, update, delete on public.social_links to authenticated;
grant usage, select on sequence public.social_links_id_seq to authenticated;
